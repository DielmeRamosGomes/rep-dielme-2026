dia_semana = input("Digite um dia da semana: ")

if dia_semana == "Domingo":
    print("Evento de Domingo")
elif dia_semana == "Sábado":
    print("Evento de Sábado")
elif dia_semana == "Segunda":
    print("Evento de Segunda")
elif dia_semana == "Terça":
    print("Evento de Terça")
elif dia_semana == "Quarta":
    print("Evento de Quarta")
elif dia_semana == "Quinta":
    print("Evento de Quinta")
elif dia_semana == "Sexta":
    print("Evento de Sexta")
else:
    print("Digite um nome da semana")
    
